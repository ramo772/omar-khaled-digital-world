import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const outputDirectory = path.resolve('dist/client');
const productionBranch = process.env.CF_PAGES_BRANCH === 'main';
const siteUrl = process.env.VITE_SITE_URL?.replace(/\/$/, '');
const indexable = process.env.VITE_SITE_INDEX === 'true';

if (productionBranch && (!siteUrl || !indexable)) {
  throw new Error(
    'Production Pages builds require VITE_SITE_URL=https://<project>.pages.dev and VITE_SITE_INDEX=true.',
  );
}

if (siteUrl) {
  const parsed = new URL(siteUrl);
  if (
    parsed.protocol !== 'https:' ||
    parsed.pathname !== '/' ||
    parsed.search ||
    parsed.hash
  ) {
    throw new Error(
      'VITE_SITE_URL must be an HTTPS origin without a path, query, hash, or trailing slash.',
    );
  }
}

const requiredFiles = [
  'index.html',
  '404.html',
  'index.rsc',
  'favicon.svg',
  'og.jpg',
  'avatar/omar-loader-portrait-v2.png',
  'brand/tobi.png',
  'brand/vois.png',
  'fallback/world-day.webp',
  'fallback/world-night.webp',
];

for (const file of requiredFiles) {
  await stat(path.join(outputDirectory, file));
}

for (const forbidden of ['_worker.js', '_routes.json', 'functions']) {
  try {
    await stat(path.join(outputDirectory, forbidden));
    throw new Error(
      `${forbidden} must not be present in the static Pages output.`,
    );
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
}

const html = await readFile(path.join(outputDirectory, 'index.html'), 'utf8');
const rsc = await readFile(path.join(outputDirectory, 'index.rsc'), 'utf8');

if (html.includes('/_next/image') || rsc.includes('/_next/image')) {
  throw new Error(
    'The static export still references the runtime Next.js image optimizer.',
  );
}

if (!html.includes('"initialCacheKind":"static"')) {
  throw new Error('The root route was not emitted as a static Vinext route.');
}

if (siteUrl) {
  const metadataChecks = [
    `<link rel="canonical" href="${siteUrl}"`,
    `<meta property="og:url" content="${siteUrl}"`,
    `<meta property="og:image" content="${siteUrl}/og.jpg"`,
    `<meta name="twitter:image" content="${siteUrl}/og.jpg"`,
  ];

  for (const expected of metadataChecks) {
    if (!html.includes(expected)) {
      throw new Error(`Missing production metadata in index.html: ${expected}`);
    }
  }
}

if (
  indexable &&
  !html.includes('<meta name="robots" content="index, follow"')
) {
  throw new Error(
    'VITE_SITE_INDEX=true did not produce indexable robots metadata.',
  );
}

const referencedRootAssets = new Set(
  [...html.matchAll(/(?:href|src)="(\/[^"]+)"/g)]
    .map((match) => match[1].split(/[?#]/, 1)[0])
    .filter((assetPath) => assetPath !== '/' && !assetPath.startsWith('/#')),
);

for (const assetPath of referencedRootAssets) {
  await stat(
    path.join(outputDirectory, decodeURIComponent(assetPath.slice(1))),
  );
}

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(directory, entry.name);
      return entry.isDirectory() ? collectFiles(fullPath) : [fullPath];
    }),
  );
  return nested.flat();
}

const files = await collectFiles(outputDirectory);
if (files.length > 20_000) {
  throw new Error(
    `Cloudflare Pages allows 20,000 files; this export contains ${files.length}.`,
  );
}

const maxAssetBytes = 25 * 1024 * 1024;
for (const file of files) {
  const fileStat = await stat(file);
  if (fileStat.size > maxAssetBytes) {
    throw new Error(
      `${path.relative(outputDirectory, file)} exceeds Cloudflare Pages' 25 MiB asset limit.`,
    );
  }
}

const headers = `# Generated by scripts/prepare-pages-output.mjs for Cloudflare Pages
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
  Permissions-Policy: camera=(), geolocation=(), microphone=()

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/avatar/*
  Cache-Control: public, max-age=3600, must-revalidate

/brand/*
  Cache-Control: public, max-age=3600, must-revalidate

/fallback/*
  Cache-Control: public, max-age=3600, must-revalidate

/og.jpg
  Cache-Control: public, max-age=3600, must-revalidate

/favicon.svg
  Cache-Control: public, max-age=3600, must-revalidate
`;

await writeFile(path.join(outputDirectory, '_headers'), headers, 'utf8');

console.log(
  `Cloudflare Pages export verified: ${files.length} files, static HTML/RSC, direct image assets, and social metadata${
    siteUrl ? ` for ${siteUrl}` : ' (preview/noindex mode)'
  }.`,
);
